#!/usr/bin/env python3
"""Generates media/android/framework-resources.txt from an Android SDK platform.

The file maps public Android framework resource IDs (0x01xxxxxx) to their
names, and lists the enum/flag values of framework attributes. BogusMips embeds
it to show `@android:style/Theme` instead of `@0x01030005`, and
`android:protectionLevel="signature"` instead of `0x2`.

Usage: tools/gen_framework_resources.py ~/Library/Android/sdk/platforms/android-36
"""
import os
import sys
import xml.etree.ElementTree as ET

platform = sys.argv[1]
values = os.path.join(platform, "data", "res", "values")
out_path = os.path.join(os.path.dirname(__file__), "..", "media", "android", "framework-resources.txt")

ids = {}  # id -> (type, name)
root = ET.parse(os.path.join(values, "public-final.xml")).getroot()
for el in root:
    if el.tag == "public" and el.get("id"):
        ids[int(el.get("id"), 16)] = (el.get("type"), el.get("name"))
    elif el.tag == "staging-public-group-final":
        next_id = int(el.get("first-id"), 16)
        for child in el:
            if child.tag == "public":
                if child.get("name"):
                    ids[next_id] = (el.get("type"), child.get("name"))
                next_id += 1

attr_ids = {name: rid for rid, (t, name) in ids.items() if t == "attr"}
symbols = {}  # attr id -> (kind, [(name, value)])
for file in ("attrs.xml", "attrs_manifest.xml"):
    path = os.path.join(values, file)
    if not os.path.exists(path):
        continue
    for attr in ET.parse(path).getroot().iter("attr"):
        rid = attr_ids.get(attr.get("name"))
        items = [(c.tag, c.get("name"), c.get("value")) for c in attr if c.tag in ("enum", "flag")]
        if rid is None or not items or rid in symbols:
            continue
        symbols[rid] = (items[0][0], [(n, v) for _, n, v in items])

with open(out_path, "w") as out:
    out.write("# Generated by tools/gen_framework_resources.py from the Android SDK\n")
    out.write(f"# ({os.path.basename(os.path.normpath(platform))}). Android framework resource\n")
    out.write("# definitions are from AOSP, licensed under the Apache License 2.0.\n")
    out.write("# r <id> <type> <name>        public resource\n")
    out.write("# e|f <attr id> name=value... enum / flag values of an attribute\n")
    for rid in sorted(ids):
        t, name = ids[rid]
        out.write(f"r {rid:08x} {t} {name}\n")
    for rid in sorted(symbols):
        kind, items = symbols[rid]
        out.write(f"{kind[0]} {rid:08x} " + " ".join(f"{n}={v}" for n, v in items) + "\n")
print(f"{len(ids)} resources, {len(symbols)} attributes with symbols -> {out_path}")
